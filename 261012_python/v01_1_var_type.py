x = 10                      # int(정수)
y = 3.14                    # float(실수)
name = "Python"             # 문자열(큰 따옴표 | 작은 따옴표 모두 가능)
is_fun = True               # 논리값(True / False)
colors = ["red", "green"]   # 리스트(순서 있음, 수정 가능)
coords = (10, 20)           # 튜플(순서있음, 수정 불가)
person = {"name": "Tom"}    # 딕셔너리(키-값 쌍)
nums = {1, 2, 3}            # 집합(중복 불가, 순서 없음)
nothing = None              # NoneType(값 없음)

print("x type : ", type(x))
print("y type : ", type(y))
print("name type : ", type(name))
print("is_fun type : ", type(is_fun))
print("colors type : ", type(colors))
print("coords type : ", type(coords))
print("person type : ", type(person))
print("nums type : ", type(nums))
print("nothing type : ", type(nothing))

